/* Content store: published content.js + an optional local draft (this browser only). */
(function () {
  const KEY = "rv-draft-v1";
  const clone = (o) => JSON.parse(JSON.stringify(o));
  const published = clone(window.SITE_DEFAULTS);
  const listeners = new Set();

  function readDraft() {
    try {
      const raw = localStorage.getItem(KEY);
      return raw ? JSON.parse(raw) : null;
    } catch (e) {
      return null;
    }
  }

  // Draft wins, but fill in any design keys added since the draft was saved.
  const draft = readDraft();
  let data = draft ? draft : clone(published);
  data.design = Object.assign({}, published.design, data.design || {});

  let saveTimer = null;

  window.Store = {
    get data() { return data; },
    hasDraft() { return readDraft() !== null; },

    // kind: "design" (no re-render needed) or "content"
    change(kind) {
      clearTimeout(saveTimer);
      saveTimer = setTimeout(() => {
        try { localStorage.setItem(KEY, JSON.stringify(data)); } catch (e) {}
        listeners.forEach((fn) => fn("saved"));
      }, 250);
      listeners.forEach((fn) => fn(kind));
    },

    replace(next) {
      data = next;
      data.design = Object.assign({}, published.design, data.design || {});
      this.change("all");
    },

    discardDraft() {
      try { localStorage.removeItem(KEY); } catch (e) {}
      data = clone(published);
      listeners.forEach((fn) => fn("all"));
      listeners.forEach((fn) => fn("saved"));
    },

    exportJS() {
      return (
        "/* Published site content — generated by /admin. Replace this file to publish. */\n" +
        "window.SITE_DEFAULTS = " + JSON.stringify(data, null, 2) + ";\n"
      );
    },

    on(fn) { listeners.add(fn); }
  };
})();
